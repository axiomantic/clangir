    def test_cpp_advanced_features(self) -> None:
        """Test C++ smart pointers, move semantics, operators, and container iterators."""
        h = Header(
            path="test.hpp",
            declarations=[
                Struct(
                    name="MyVector",
                    fields=[
                        Field("ptr", CType("std::shared_ptr<int>")),
                    ],
                    methods=[
                        Function(
                            name="operator[]",
                            return_type=Reference(CType("int")),
                            parameters=[Parameter("index", CType("size_t"))],
                        ),
                        Function(
                            name="push",
                            return_type=CType("void"),
                            parameters=[Parameter("val", Reference(CType("int"), is_rvalue=True))],
                        ),
                        Function(
                            name="begin",
                            return_type=Pointer(CType("int")),
                        ),
                        Function(
                            name="end",
                            return_type=Pointer(CType("int")),
                        ),
                    ],
                )
            ],
        )
        out = write_nim(h, header_path="test.hpp")
        expected = textwrap.dedent("""\
            # Generated by headerkit

            type
              SharedPtr*[T] {.importcpp: "std::shared_ptr<'0>", header: "<memory>".} = object
              MyVector* {.importcpp: "MyVector", header: "test.hpp", bycopy.} = object
                `ptr`*: SharedPtr[cint]


            proc get*[T](p: SharedPtr[T]): ptr T {.importcpp: "#.get()", header: "<memory>".}

            proc reset*[T](p: var SharedPtr[T]) {.importcpp: "#.reset()", header: "<memory>".}

            proc useCount*[T](p: SharedPtr[T]): clong {.importcpp: "#.use_count()", header: "<memory>".}

            proc `[]`*(this: var MyVector, index: csize_t): var cint {.importcpp: "#[@]", header: "test.hpp".}

            proc push*(this: var MyVector, val: sink cint) {.importcpp: "#.push(@)", header: "test.hpp".}

            proc begin*(this: var MyVector): ptr cint {.importcpp: "#.begin(@)", header: "test.hpp".}

            proc `end`*(this: var MyVector): ptr cint {.importcpp: "#.end(@)", header: "test.hpp".}

            iterator items*(this: var MyVector): auto = {.inline.}
              var it = this.begin()
              while it != this.end():
                yield it[]
                inc it
        """)
        assert out == expected

